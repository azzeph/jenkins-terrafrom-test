#!/usr/bin/env python3
"""
Generate an Ansible INI inventory from Terraform outputs.

The script reads the `vms` output of the Terraform configuration (via
`terraform output -json vms`) and writes an INI inventory containing one
entry per VM with `ansible_host`, `ansible_user` and the hostname.

By default the inventory is written to

    ansible/inventory/<branch>/hosts.ini

where <branch> is the current git branch (a directory per branch keeps the
inventories of parallel environments apart).

Examples
--------
    # from the repository root (uses the current git branch)
    python3 scripts/terraform_inventory.py

    # explicit branch and terraform dir
    python3 scripts/terraform_inventory.py --branch feature-x --terraform-dir .

    # only print, do not write a file
    python3 scripts/terraform_inventory.py --dry-run

    # use it directly as an Ansible inventory (executable inventory)
    ansible-playbook -i scripts/terraform_inventory.py site.yml

Exit codes
----------
    0  inventory generated
    1  terraform output could not be read / parsed
    2  invalid arguments
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any


DEFAULT_INVENTORY_ROOT = Path("ansible") / "inventory"
DEFAULT_OUTPUT_NAME = "hosts.ini"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def log(message: str) -> None:
    """Diagnostics go to stderr.

    NOTE: when this script is used as an Ansible *executable inventory*,
    anything written to stderr is shown by Ansible as an [ERROR] line, so we
    only write to stderr for real warnings/errors and stay quiet otherwise.
    """
    print(f"[terraform_inventory] {message}", file=sys.stderr)


def debug(message: str) -> None:
    """Verbose diagnostics — only shown when TF_INVENTORY_DEBUG is set."""
    if os.environ.get("TF_INVENTORY_DEBUG"):
        log(message)


def detect_git_branch(start_dir: Path) -> str:
    """Return a filesystem-safe current git branch name."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=start_dir,
            capture_output=True,
            text=True,
            check=True,
        )
        branch = out.stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        branch = ""

    if not branch or branch == "HEAD":
        # Detached HEAD or not a git repo: fall back to an env var or 'local'.
        branch = os.environ.get("BRANCH_NAME", "local")

    return sanitize_branch(branch)


def sanitize_branch(branch: str) -> str:
    """Make a branch name safe to use as a directory name."""
    safe = branch.strip()
    for ch in ("/", "\\", " ", ":"):
        safe = safe.replace(ch, "-")
    while "--" in safe:
        safe = safe.replace("--", "-")
    return safe.strip("-.") or "local"


def run_terraform_output(terraform_dir: Path, key: str) -> Any:
    """Run `terraform output -json <key>` and return the parsed JSON."""
    cmd = ["terraform", "output", "-json", key]
    debug(f"running: {' '.join(cmd)} (cwd={terraform_dir})")
    try:
        result = subprocess.run(
            cmd,
            cwd=terraform_dir,
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        log("ERROR: terraform binary not found in PATH")
        raise SystemExit(1)

    if result.returncode != 0:
        log(f"ERROR: terraform output failed:\n{result.stderr.strip()}")
        raise SystemExit(1)

    raw = result.stdout.strip()
    if not raw:
        log(f"ERROR: terraform output '{key}' is empty")
        raise SystemExit(1)

    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        log(f"ERROR: cannot parse terraform output: {exc}\n{raw}")
        raise SystemExit(1)


# ---------------------------------------------------------------------------
# Inventory rendering
# ---------------------------------------------------------------------------

def build_inventory(
    vms: dict[str, dict[str, Any]],
    group: str,
    include_mac: bool = True,
    host_key_checking: bool = False,
) -> str:
    """Render an INI inventory from the `vms` terraform output."""
    if not vms:
        raise SystemExit(1)

    lines: list[str] = []
    lines.append("# Generated by scripts/terraform_inventory.py — do not edit by hand.")
    lines.append("# Source: terraform output -json vms")
    lines.append("")

    # Group every VM under a single group plus an `all`-level listing.
    body: list[str] = []
    body.append(f"[{group}]")
    for name in sorted(vms):
        vm = vms[name]
        ip = vm.get("ip")
        user = vm.get("user") or "ubuntu"
        hostname = vm.get("hostname") or name

        if not ip:
            log(f"WARNING: VM '{name}' has no ip — skipping")
            continue

        vars_: list[str] = [
            f"ansible_host={ip}",
            f"ansible_user={user}",
            f"hostname={hostname}",
        ]
        if include_mac and vm.get("mac"):
            vars_.append(f"ansible_mac={vm['mac']}")
        body.append(f"{name} " + " ".join(vars_))

    body.append("")

    body.append("[all:children]")
    body.append(group)
    body.append("")

    body.append("[all:vars]")
    body.append("ansible_python_interpreter=/usr/bin/python3")
    if not host_key_checking:
        body.append(
            "ansible_ssh_common_args="
            "'-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null'"
        )
    body.append("")

    return "\n".join(lines + body)


# --------------------------------------------------------------------------
# Ansible dynamic-inventory protocol
# --------------------------------------------------------------------------

def _host_vars(vm: dict[str, Any]) -> dict[str, Any]:
    """Build the Ansible host variables for a single VM."""
    return {
        "ansible_host": vm.get("ip"),
        "ansible_user": vm.get("user") or "ubuntu",
        "hostname": vm.get("hostname"),
        "ansible_mac": vm.get("mac"),
    }


def _dynamic_inventory(vms: dict[str, dict[str, Any]], group: str) -> dict[str, Any]:
    """Build a JSON inventory in the format Ansible expects from --list.

    Ansible wants each group's ``hosts`` to be a LIST of host names (not a
    mapping); per-host variables go into ``_meta.hostvars``.
    """
    hostnames: list[str] = []
    hostvars: dict[str, Any] = {}
    for name, vm in sorted(vms.items()):
        if not vm.get("ip"):
            log(f"WARNING: VM '{name}' has no ip — skipping")
            continue
        hostnames.append(name)
        hostvars[name] = _host_vars(vm)

    return {
        group: {"hosts": hostnames},
        "_meta": {"hostvars": hostvars},
    }


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate an Ansible INI inventory from Terraform outputs.",
    )
    parser.add_argument(
        "--terraform-dir",
        default=None,
        help="Directory containing the Terraform configuration "
             "(default: CWD if it looks like Terraform, else the script's parent dir).",
    )
    parser.add_argument(
        "--branch",
        default=None,
        help="Branch name used for the inventory directory "
             "(default: current git branch, or $BRANCH_NAME, or 'local').",
    )
    parser.add_argument(
        "--inventory-root",
        default=str(DEFAULT_INVENTORY_ROOT),
        help=f"Root directory for inventories (default: {DEFAULT_INVENTORY_ROOT}).",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Explicit output file. Overrides --inventory-root/--branch.",
    )
    parser.add_argument(
        "--group",
        default="vms",
        help="Ansible group name that holds the VMs (default: vms).",
    )
    parser.add_argument(
        "--no-mac",
        action="store_true",
        help="Do not include ansible_mac.",
    )
    parser.add_argument(
        "--host-key-checking",
        action="store_true",
        help="Keep SSH host key checking enabled (default: disabled).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the inventory to stdout instead of writing a file.",
    )
    parser.add_argument(
        "--list",
        action="store_true",
        help="Ansible dynamic-inventory protocol: print JSON inventory and exit.",
    )
    parser.add_argument(
        "--host",
        default=None,
        help="Ansible dynamic-inventory protocol: print one host's vars as JSON.",
    )
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)

    # When invoked as an Ansible executable inventory the CWD is arbitrary
    # (Ansible runs the script from wherever), so resolve the Terraform
    # directory from the script location unless --terraform-dir was given.
    if args.terraform_dir is not None:
        terraform_dir = Path(args.terraform_dir).expanduser().resolve()
    elif (Path.cwd() / "outputs.tf").exists() or (Path.cwd() / ".terraform").exists():
        terraform_dir = Path.cwd().resolve()
    else:
        terraform_dir = Path(__file__).resolve().parent.parent

    if not (terraform_dir / "outputs.tf").exists() and not (
        terraform_dir / ".terraform"
    ).exists():
        log(f"WARNING: {terraform_dir} does not look like a Terraform directory")

    branch = sanitize_branch(args.branch) if args.branch else detect_git_branch(terraform_dir)

    vms = run_terraform_output(terraform_dir, "vms")
    if not isinstance(vms, dict):
        log("ERROR: 'vms' output is not a map")
        return 1

    # --- Ansible dynamic-inventory protocol -------------------------------
    if args.host is not None:
        vm = vms.get(args.host)
        print(json.dumps(_host_vars(vm) if vm else {}, indent=2))
        return 0

    if args.list:
        print(json.dumps(_dynamic_inventory(vms, args.group), indent=2))
        return 0

    inventory = build_inventory(
        vms,
        group=args.group,
        include_mac=not args.no_mac,
        host_key_checking=args.host_key_checking,
    )

    if args.dry_run:
        print(inventory)
        return 0

    if args.output:
        out_path = Path(args.output).expanduser()
    else:
        out_path = Path(args.inventory_root).expanduser() / branch / DEFAULT_OUTPUT_NAME

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(inventory, encoding="utf-8")
    debug(f"inventory written to {out_path} ({len(vms)} hosts, branch '{branch}')")
    print(f"inventory written to {out_path} ({len(vms)} hosts, branch '{branch}')", file=sys.stderr)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except KeyboardInterrupt:
        sys.exit(130)
